def save_episode_files(output_dir: str):
    """Save all 14 episodes as individual JSON files."""
    os.makedirs(output_dir, exist_ok=True)
    saved_paths = []
    for ep in EPISODES:
        file_name = f"{ep['id']}_{ep['title']}.json"
        full_path = os.path.join(output_dir, file_name)
        with open(full_path, "w", encoding="utf-8") as f:
            json.dump({
                "id": ep["id"],
                "title": ep["title"],
                "display_title": ep["display_title"],
                "slot": ep["slot"],
                "target_time": ep["target_time"],
                "day": ep["day"],
                "voice": ep["voice"],
                "style": ep["style"],
                "desc": ep["desc"],
                "tags": ep["tags"],
                "beats": ep["beats"]
            }, f, ensure_ascii=False, indent=2)
        saved_paths.append(full_path)
    print(f"✅ Successfully saved {len(saved_paths)} episode JSON files to: {output_dir}")
    return saved_paths


