let customQuestions = null;

export function setCustomQuestions(list) {
  if (Array.isArray(list) && list.length > 0) {
    customQuestions = list;
    try {
      localStorage.setItem('jsr-custom-questions-v1', JSON.stringify(list));
    } catch (e) {}
  } else {
    customQuestions = null;
    try {
      localStorage.removeItem('jsr-custom-questions-v1');
    } catch (e) {}
  }
}

export function loadSavedCustomQuestions() {
  try {
    const raw = localStorage.getItem('jsr-custom-questions-v1');
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        customQuestions = parsed;
        return customQuestions;
      }
    }
  } catch (e) {}
  customQuestions = null;
  return null;
}

export function getActiveQuestions() {
  if (!customQuestions) {
    loadSavedCustomQuestions();
  }
  return customQuestions && customQuestions.length > 0 ? customQuestions : QUESTIONS;
}

export function isUsingCustomQuestions() {
  if (!customQuestions) loadSavedCustomQuestions();
  return !!(customQuestions && customQuestions.length > 0);
}

/**
 * สุ่มคำถามให้แต่ละประตู แยกตามโซน เพื่อให้เนื้อหาไล่ระดับตามด่าน
 * และพยายามไม่ให้คำถามซ้ำกันภายในรอบเดียว
 */
export function assignQuestions(gates, rng) {
  const active = getActiveQuestions();
  const pool = [[], [], []];
  for (const q of active) {
    const z = Math.max(0, Math.min(2, typeof q.zone === 'number' ? q.zone : 0));
    pool[z].push(q);
  }

  // หากโซนใดไม่มีคำถามเลย ให้ยืมคำถามจากโซนที่มีมาเติมเพื่อไม่ให้เกมค้าง
  const allAvailable = active.slice();
  for (let z = 0; z < 3; z++) {
    if (pool[z].length === 0) {
      pool[z] = allAvailable.length > 0 ? allAvailable.slice() : QUESTIONS.slice();
    }
  }

  const needs = [[], [], []];
  for (const g of gates) needs[g.zone].push(g);

  const assign = new Map();
  for (let z = 0; z < 3; z++) {
    const list = pool[z].slice();
    for (let i = list.length - 1; i > 0; i--) {
      const j = Math.floor(rng.next() * (i + 1));
      [list[i], list[j]] = [list[j], list[i]];
    }
    needs[z].forEach((g, i) => {
      if (!list.length) return;
      assign.set(g.index, list[i % list.length]);
    });
  }
  return assign;
}

export function topicList() {
  const active = getActiveQuestions();
  const set = new Set();
  for (const q of active) set.add(q.topic);
  return [...set];
}
